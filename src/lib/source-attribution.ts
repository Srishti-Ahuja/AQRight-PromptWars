/**
 * Pure client-side calculations and helpers for the Source Attribution Breakdown.
 * Mirrors backend logic to ensure instantaneous offline responsiveness with zero network latency.
 */

import type { SourceAttributionReport, SourceDriverMetric, SourceDriverType, TelemetryData } from '../types';

export function calculateSourceAttribution(
  telemetry: TelemetryData,
  windDirectionDeg = 315
): SourceAttributionReport {
  const { current, stationName, cpcb } = telemetry;
  const pm25 = Math.max(0.1, current.pm25);
  const pm10 = Math.max(0.1, current.pm10);
  const no2 = Math.max(0, current.no2);
  const co = Math.max(0, current.co);
  const o3 = Math.max(0, current.o3);
  const blh = Math.max(10, current.boundaryLayerHeight);
  const windSpd = Math.max(0, current.windSpeed);

  const ratio = Math.round((pm25 / Math.max(pm25, pm10)) * 100) / 100;
  const isInversion = current.isTrappedSurfaceSmog || blh < 450;

  // 1. Raw scores
  const inversionSeverity = isInversion ? Math.max(0, (450 - blh) / 350) : 0;
  const fineExcess = Math.max(0, ratio - 0.45);
  const biomassRaw = pm25 * 0.4 * (1 + fineExcess * 2) * (1 + inversionSeverity * 0.8);

  const coarseFraction = Math.max(0, 1 - ratio);
  const dustRaw = pm10 * 0.35 * (1 + coarseFraction * 1.5) * (1 + Math.min(1.5, windSpd / 12));

  const no2Factor = Math.min(3, no2 / 40);
  const coFactor = Math.min(3, co / 1.0);
  const trafficRaw = (no2 * 1.2 + co * 25) * (0.8 + 0.4 * (no2Factor + coFactor));

  const ozoneFactor = Math.min(3, o3 / 50);
  const photoRaw = o3 * 0.8 * (0.5 + 0.5 * ozoneFactor);

  // 2. Normalize percentages
  let totalRaw = biomassRaw + dustRaw + trafficRaw + photoRaw;
  if (totalRaw <= 0) totalRaw = 1.0;

  const pBiomass = Math.round((biomassRaw / totalRaw) * 1000) / 10;
  const pDust = Math.round((dustRaw / totalRaw) * 1000) / 10;
  const pTraffic = Math.round((trafficRaw / totalRaw) * 1000) / 10;
  const pPhoto = Math.max(0, Math.round((100 - (pBiomass + pDust + pTraffic)) * 10) / 10);

  const drivers: SourceDriverMetric[] = [
    {
      driverType: 'biomass_inversion' as SourceDriverType,
      label: 'Biomass Smoke & Thermal Inversion',
      contributionPercent: pBiomass,
      severity: pBiomass >= 40 ? 'high' : pBiomass >= 20 ? 'moderate' : 'low',
      rationale: `Fine combustion fraction (PM2.5/PM10: ${ratio.toFixed(2)}) combined with shallow boundary mixing layer (${Math.round(blh)}m) traps crop stubble, biomass burning, and heating smoke near ground level.`,
      metricsSnapshot: `PM2.5/PM10: ${ratio.toFixed(2)} | Mixing Layer: ${Math.round(blh)}m`,
      iconName: 'Flame',
    },
    {
      driverType: 'surface_road_dust' as SourceDriverType,
      label: 'Road Dust & Construction Surface Resuspension',
      contributionPercent: pDust,
      severity: pDust >= 35 ? 'high' : pDust >= 20 ? 'moderate' : 'low',
      rationale: `Coarse aerodynamic dust (PM10: ${Math.round(pm10)} µg/m³) generated by vehicular shear and dry street surfaces. Highly concentrated on ground and 1st-floor apartments.`,
      metricsSnapshot: `Coarse PM10: ${Math.round(pm10)} µg/m³ | Surface Wind: ${Math.round(windSpd)} km/h`,
      iconName: 'Tornado',
    },
    {
      driverType: 'vehicular_exhaust' as SourceDriverType,
      label: 'Vehicular Exhaust & Urban Transit Corridors',
      contributionPercent: pTraffic,
      severity: pTraffic >= 30 ? 'high' : pTraffic >= 15 ? 'moderate' : 'low',
      rationale: `Direct tailpipe NO2 (${Math.round(no2)} µg/m³) and CO (${co.toFixed(1)} mg/m³) from diesel commercial transit and arterial congestion. Readily penetrates open two-wheelers and auto-rickshaws.`,
      metricsSnapshot: `NO2: ${Math.round(no2)} µg/m³ | CO: ${co.toFixed(1)} mg/m³`,
      iconName: 'Car',
    },
    {
      driverType: 'photochemical_smog' as SourceDriverType,
      label: 'Photochemical Secondary Smog & Ozone',
      contributionPercent: pPhoto,
      severity: pPhoto >= 25 ? 'high' : pPhoto >= 10 ? 'moderate' : 'low',
      rationale: `Secondary tropospheric ozone (${Math.round(o3)} µg/m³) catalyzed by solar radiation reacting with unburnt hydrocarbons. Peaks during bright afternoon windows.`,
      metricsSnapshot: `Ozone (O3): ${Math.round(o3)} µg/m³`,
      iconName: 'Sun',
    },
  ];

  drivers.sort((a, b) => b.contributionPercent - a.contributionPercent);
  const dominant = drivers[0].driverType;

  // Cardinal direction conversion
  const val = Math.floor(windDirectionDeg / 22.5 + 0.5);
  const cardinals = ['N', 'NNE', 'NE', 'ENE', 'E', 'ESE', 'SE', 'SSE', 'S', 'SSW', 'SW', 'WSW', 'W', 'WNW', 'NW', 'NNW'];
  const windCard = cardinals[val % 16];

  let causal = '';
  let action = '';

  if (dominant === 'biomass_inversion') {
    causal = `Atmospheric lid effect: Nocturnal boundary layer dropped to ${Math.round(blh)}m, preventing vertical smoke dispersion (PM2.5/PM10: ${ratio.toFixed(2)}) carried by ${windCard} winds.`;
    action = 'Seal perimeter balcony gaps, run HEPA purifiers in closed rooms, and postpone morning outdoor workouts until the solar inversion lift.';
  } else if (dominant === 'surface_road_dust') {
    causal = `Mechanical surface resuspension: Elevated PM10 (${Math.round(pm10)} µg/m³) indicates heavy traffic shearing dry road silt under ${windCard} winds of ${Math.round(windSpd)} km/h.`;
    action = 'Immediately halt dry broom sweeping (jhadu) in favor of wet microfiber mopping; keep roadside ground-floor sliding doors shut.';
  } else if (dominant === 'vehicular_exhaust') {
    causal = `Transit corridor stagnation: Elevated NO2 (${Math.round(no2)} µg/m³) and combustion gases are lingering due to low lateral wind ventilation (${Math.round(windSpd)} km/h).`;
    action = 'Two-wheeler and auto commuters must wear snug N95 respirators; automobile drivers should keep cabin HVAC on recirculation mode.';
  } else {
    causal = `Photochemical oxidative episode: Elevated ozone (${Math.round(o3)} µg/m³) is driving secondary aerosol formation under direct solar insolation.`;
    action = 'Avoid vigorous midday running between 1:00 PM and 4:00 PM; sensitive family members should remain indoors.';
  }

  return {
    stationName,
    aqi: cpcb.aqi,
    category: cpcb.category,
    dominantDriver: dominant,
    causalSummary: causal,
    drivers,
    meteorology: {
      mixingLayerM: Math.round(blh),
      isInversionTrapped: isInversion,
      windSpeedKmh: Math.round(windSpd),
      windCardinal: windCard,
      temperatureC: Math.round(current.temperature),
      humidityPercent: Math.round(current.relativeHumidity),
      pm25ToPm10Ratio: ratio,
    },
    actionImplication: action,
  };
}
